z = zipfile.ZipFile(DOCX)
x = z.read('word/document.xml').decode('utf8')
rels = z.read('word/_rels/document.xml.rels').decode('utf8')
rmap = {}
for m in re.finditer(r'<Relationship\b[^>]*>', rels):
    t = m.group(0)
    i = re.search(r'Id="([^"]+)"', t)
    g = re.search(r'Target="([^"]+)"', t)
    if i and g:
        rmap[i.group(1)] = g.group(1)

row_images = {}  # part row number -> [media paths]
for t in re.findall(r'<w:tbl>.*?</w:tbl>', x, flags=re.S):
    for r in re.findall(r'<w:tr[ >].*?</w:tr>', t, flags=re.S):
        cells = re.findall(r'<w:tc>.*?</w:tc>', r, flags=re.S)
        txt = [''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', c)).strip() for c in cells]
        nums = [s for s in txt if re.fullmatch(r'\d{1,3}', s)]
        imgs = [rmap[e] for c in cells for e in re.findall(r'r:embed="([^"]+)"', c) if e in rmap]
        if nums and imgs:
            row_images[int(nums[-1])] = imgs

out_dir = os.path.join(ROOT, 'public', 'img', 'parts')
os.makedirs(out_dir, exist_ok=True)
items = []
for (row, part_no, name, material, weight, variants, note) in P:
    imgs = row_images.get(row, [])
    files = []
    for k, media in enumerate(imgs):
        ext = os.path.splitext(media)[1].lower().replace('.jpeg', '.jpg')
        fn = f'part-{row}' + (f'-{k+1}' if len(imgs) > 1 else '') + ext
        with open(os.path.join(out_dir, fn), 'wb') as f:
            f.write(z.read('word/' + media))
        files.append('/img/parts/' + fn)
    for vi, (code, variant) in enumerate(variants):
        image = None
        if files:
            image = files[0]
            if len(files) > 1:  # two photos: second photo belongs to the second half of the variants
                image = files[0] if vi < len(variants) / 2 else files[1]
        items.append(dict(code=code, part_no=part_no, name=name, variant=variant, material=material,
                          weight_g=weight, row_no=row, image=image, note=note if vi == 0 else ''))

codes = [i['code'] for i in items]
assert len(codes) == len(set(codes)), [c for c in codes if codes.count(c) > 1]
with open(os.path.join(ROOT, 'server', 'seed', 'parts.json'), 'w', encoding='utf8') as f:
    json.dump(items, f, ensure_ascii=False, indent=1)
print(len(P), 'parts ->', len(items), 'items;', sum(1 for i in items if i['image']), 'with image;',
      'rows without image:', [r[0] for r in P if r[0] not in row_images])
